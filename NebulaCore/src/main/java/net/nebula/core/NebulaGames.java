    private static ItemStack cloneItem(ItemStack item) {
        return item == null ? null : item.clone();
    }

    private static final class BedWarsMatch {
        final World world;
        final int teamSize;
        final Set<UUID> all = new LinkedHashSet<>();
        final Set<UUID> red = new LinkedHashSet<>();
        final Set<UUID> blue = new LinkedHashSet<>();
        final Set<UUID> redAlive = new LinkedHashSet<>();
        final Set<UUID> blueAlive = new LinkedHashSet<>();
        boolean redBedAlive = true;
        boolean blueBedAlive = true;
        boolean finished = false;
        BedWarsMatch(World world, int teamSize) { this.world = world; this.teamSize = teamSize; }
    }

    private static final class DuelMatch {
        final World world;
        final UUID first;
        final UUID second;
        UUID botId;
        boolean finished = false;
        DuelMatch(World world, UUID first, UUID second, UUID botId) {
            this.world = world; this.first = first; this.second = second; this.botId = botId;
        }
        UUID opponent(UUID id) {
            if (second == null) return null;
            return first.equals(id) ? second : first;
        }
        Set<UUID> players() {
            Set<UUID> ids = new LinkedHashSet<>();
            if (first != null) ids.add(first);
            if (second != null) ids.add(second);
            return ids;
        }
    }

    private static final class PlayerSnapshot {
        final ItemStack[] storage;
        final ItemStack[] armor;
        final ItemStack offhand;
        final GameMode mode;
        final double health;
        final int food;
        final float saturation;
        final int level;
        final float exp;
        final boolean allowFlight;
        PlayerSnapshot(Player player) {
            storage = cloneItems(player.getInventory().getStorageContents());
            armor = cloneItems(player.getInventory().getArmorContents());
            offhand = cloneItem(player.getInventory().getItemInOffHand());
            mode = player.getGameMode();
            health = player.getHealth();
            food = player.getFoodLevel();
            saturation = player.getSaturation();
            level = player.getLevel();
            exp = player.getExp();
            allowFlight = player.getAllowFlight();
        }
        static PlayerSnapshot capture(Player player) { return new PlayerSnapshot(player); }
        void restore(Player player) {
            player.getInventory().clear();
            player.getInventory().setStorageContents(cloneItems(storage));
            player.getInventory().setArmorContents(cloneItems(armor));
            player.getInventory().setItemInOffHand(cloneItem(offhand));
            player.setGameMode(mode);
            player.setAllowFlight(allowFlight);
            player.setFlying(false);
            player.setHealth(Math.min(player.getMaxHealth(), Math.max(1.0, health)));
            player.setFoodLevel(food);
            player.setSaturation(saturation);
            player.setLevel(level);
            player.setExp(exp);
            player.setFireTicks(0);
        }
        private static ItemStack[] cloneItems(ItemStack[] source) {
            ItemStack[] copy = new ItemStack[source.length];
            for (int i = 0; i < source.length; i++) copy[i] = cloneItem(source[i]);
            return copy;
        }
    }
